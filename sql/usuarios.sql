
BEGIN;

CREATE TABLE rol (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(30) NOT NULL UNIQUE
        CHECK (nombre IN ('ADMINISTRADOR','OPERADOR','CLIENTE')),
    descripcion VARCHAR(150),
    estado VARCHAR(10) NOT NULL DEFAULT 'ACTIVO'
        CHECK (estado IN ('ACTIVO','INACTIVO'))
);

CREATE TABLE usuario (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    rol_id INTEGER NOT NULL REFERENCES rol(id),
    estado VARCHAR(10) NOT NULL DEFAULT 'ACTIVO'
        CHECK (estado IN ('ACTIVO','INACTIVO')),
    ultima_conexion TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE cliente (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL UNIQUE REFERENCES usuario(id),
    primer_nombre VARCHAR(50) NOT NULL,
    segundo_nombre VARCHAR(50),
    apellido VARCHAR(50) NOT NULL,
    dni VARCHAR(13) NOT NULL UNIQUE,
    nacionalidad VARCHAR(50),
    direccion VARCHAR(200),
    telefono VARCHAR(15),
    correo VARCHAR(120) NOT NULL UNIQUE
);

CREATE TABLE registro_auditoria (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL REFERENCES usuario(id),
    accion VARCHAR(30) NOT NULL
        CHECK (accion IN ('CREAR','MODIFICAR','DESACTIVAR','ACTIVAR')),
    entidad VARCHAR(50) NOT NULL,
    entidad_id INTEGER,
    descripcion TEXT,
    fecha_accion TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

