
BEGIN;

CREATE TABLE sala (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL UNIQUE,
    estado VARCHAR(10) NOT NULL DEFAULT 'ACTIVA'
        CHECK (estado IN ('ACTIVA','INACTIVA'))
);

CREATE TABLE seccion (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sala_id INTEGER NOT NULL REFERENCES sala(id),
    nombre VARCHAR(50) NOT NULL,
    descripcion VARCHAR(150),
    tipo VARCHAR(10) NOT NULL
        CHECK (tipo IN ('VIP','DBOX','GENERAL')),
    precio NUMERIC(6,2) NOT NULL CHECK (precio >= 0),
    capacidad INTEGER NOT NULL CHECK (capacidad > 0),
    num_filas INTEGER NOT NULL CHECK (num_filas > 0),
    asientos_por_fila INTEGER NOT NULL CHECK (asientos_por_fila > 0),
    UNIQUE (sala_id, nombre),
    UNIQUE (id, sala_id),
    CHECK (capacidad = num_filas * asientos_por_fila),
    CHECK (
        (tipo = 'VIP' AND precio = 15.00) OR
        (tipo = 'DBOX' AND precio = 10.00) OR
        (tipo = 'GENERAL' AND precio = 5.00)
    )
);

CREATE TABLE fila (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seccion_id INTEGER NOT NULL REFERENCES seccion(id),
    letra CHAR(1) NOT NULL,
    UNIQUE (seccion_id, letra)
);

CREATE TABLE asiento (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fila_id INTEGER NOT NULL REFERENCES fila(id),
    numero INTEGER NOT NULL CHECK (numero > 0),
    estado VARCHAR(10) NOT NULL DEFAULT 'ACTIVO'
        CHECK (estado IN ('ACTIVO','INACTIVO')),
    UNIQUE (fila_id, numero)
);

CREATE TABLE pelicula (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    descripcion TEXT,
    genero VARCHAR(40) NOT NULL,
    duracion_min INTEGER NOT NULL CHECK (duracion_min > 0),
    clasificacion VARCHAR(10) NOT NULL
        CHECK (clasificacion IN ('TP','+12','+15','+18')),
    estado VARCHAR(10) NOT NULL DEFAULT 'ACTIVA'
        CHECK (estado IN ('ACTIVA','INACTIVA')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE funcion (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pelicula_id INTEGER NOT NULL REFERENCES pelicula(id),
    sala_id INTEGER NOT NULL REFERENCES sala(id),
    fecha DATE NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    estado VARCHAR(15) NOT NULL DEFAULT 'ACTIVA'
        CHECK (estado IN ('ACTIVA','CANCELADA','FINALIZADA')),
    CHECK (hora_fin > hora_inicio),
    UNIQUE (sala_id, fecha, hora_inicio)
);

CREATE INDEX idx_funcion_pelicula_fecha
    ON funcion (pelicula_id, fecha);

