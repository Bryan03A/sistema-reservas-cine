
BEGIN;

CREATE TABLE reserva (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    cliente_id INTEGER NOT NULL,
    funcion_id INTEGER NOT NULL,
    gestionado_por INTEGER,
    fecha_reserva TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expira_en TIMESTAMPTZ,
    estado VARCHAR(15) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado IN (
            'PENDIENTE','CONFIRMADA','CANCELADA','EXPIRADA','USADA'
        )),
    cantidad_boletos INTEGER NOT NULL
        CHECK (cantidad_boletos BETWEEN 1 AND 6),
    total NUMERIC(8,2) NOT NULL CHECK (total >= 0),
    moneda CHAR(3) NOT NULL DEFAULT 'USD',
    confirmada_en TIMESTAMPTZ,
    cancelada_en TIMESTAMPTZ
);

CREATE TABLE asiento_funcion (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    funcion_id INTEGER NOT NULL,
    asiento_id INTEGER NOT NULL,
    reserva_id INTEGER REFERENCES reserva(id),
    estado VARCHAR(12) NOT NULL DEFAULT 'DISPONIBLE'
        CHECK (estado IN ('DISPONIBLE','RESERVADO','OCUPADO')),
    bloqueado_hasta TIMESTAMPTZ,
    UNIQUE (funcion_id, asiento_id)
);

CREATE INDEX idx_asiento_funcion_reserva
    ON asiento_funcion (reserva_id);

CREATE INDEX idx_asiento_funcion_estado
    ON asiento_funcion (estado, bloqueado_hasta);

CREATE TABLE boleto (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id INTEGER NOT NULL REFERENCES reserva(id),
    asiento_funcion_id INTEGER NOT NULL UNIQUE
        REFERENCES asiento_funcion(id),
    asiento_id INTEGER NOT NULL,
    precio NUMERIC(6,2) NOT NULL CHECK (precio >= 0),
    codigo_qr VARCHAR(150) NOT NULL UNIQUE,
    estado VARCHAR(10) NOT NULL DEFAULT 'ACTIVO'
        CHECK (estado IN ('ACTIVO','USADO','ANULADO')),
    emitido_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    usado_en TIMESTAMPTZ,
    UNIQUE (reserva_id, asiento_id)
);

